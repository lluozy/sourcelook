/*
 * Build client.js from the hand-written parts.
 *
 * The browser bundle is one classic script that registers a lazy factory. There
 * is no bundler dependency: the parts share the factory closure, and the CSS is
 * inlined as a string. Run `node scripts/build.mjs` after editing src/client.
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const client = path.join(root, 'src', 'client');
const lib = path.join(root, 'renderer-lib', 'editor');

const parts = [
  '00-header.js',
  '20-i18n.js',
  '30-api.js',
  '40-monaco.js',
  '45-host-css.js',
  '50-shell.js',
  '55-icons.js',
  '58-menus.js',
  '59-context-menu.js',
  '60-tree.js',
  '65-quickopen.js',
  '66-symbols.js',
  '67-symbol-search.js',
  '68-global.js',
  '68-outline.js',
  '69-results.js',
  '70-semantic.js',
  '80-app.js',
  '85-boundary.js',
  '89-probe.js',
  '90-export.js',
];

async function read(file) {
  return fs.readFile(file, 'utf8');
}

const chunks = [];
chunks.push(`/* SourceLook client bundle - generated by scripts/build.mjs. Do not edit by hand. */\n`);
chunks.push(await read(path.join(client, '00-header.js')));
chunks.push(`\n/* --- editor adapter (ported verbatim from KernelSight) --- */\n`);
chunks.push(await read(path.join(lib, 'editor-adapter.js')));
chunks.push(`\n/* --- Monaco adapter (ported; native context menu kept) --- */\n`);
chunks.push(await read(path.join(lib, 'monaco-adapter.js')));
for (const part of parts.slice(1)) {
  const source = await read(path.join(client, part));
  chunks.push(`\n/* --- ${part} --- */\n`);
  if (part === '80-app.js') {
    const css = await read(path.join(client, 'styles.css'));
    chunks.push(`    const CSS = ${JSON.stringify(css)};\n`);
  }
  chunks.push(source);
}

const output = chunks.join('\n');
await fs.writeFile(path.join(root, 'client.js'), output, 'utf8');
console.log(`client.js: ${(Buffer.byteLength(output, 'utf8') / 1024).toFixed(1)} KB`);

